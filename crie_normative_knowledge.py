def retrieve_normative_clauses(query: str, max_clauses: int = 4) -> List[Dict[str, str]]:
    """
    Интеллектуальный поиск нормативных положений с ранжированием по релевантности.
    Возвращает точные выдержки СанПиН/приказов для цитирования и преамбул документов.
    """
    q_lower = query.lower()
    keywords = re.findall(r"[a-zа-я0-9_]{3,}", q_lower)
    
    scored_clauses = []
    
    for doc in NORMATIVE_CORPUS:
        act_title = doc["title"]
        scope = doc["scope"].lower()
        
        for clause in doc["clauses"]:
            clause_text = clause["text"].lower()
            topic = clause["topic"].lower()
            
            score = 0
            for kw in keywords:
                if kw in topic:
                    score += 4
                if kw in clause_text:
                    score += 2
                if kw in scope:
                    score += 1
            
            # Специфические медицинские триггеры
            if "корь" in q_lower and "корь" in topic:
                score += 10
            if ("дезинфекц" in q_lower or "стерилиз" in q_lower) and "дезинфекц" in topic:
                score += 10
            if "исмп" in q_lower and "исмп" in topic:
                score += 10
            if ("ординатур" in q_lower or "сесси" in q_lower) and "ординатур" in topic:
                score += 10
            if "сальмонелл" in q_lower and "сальмонелл" in topic:
                score += 10
            
            if score > 0:
                scored_clauses.append({
                    "act": doc["act"],
                    "clause": clause["clause"],
                    "topic": clause["topic"],
                    "text": clause["text"],
                    "score": score
                })
    
    # Сортировка по убыванию релевантности
    scored_clauses.sort(key=lambda x: x["score"], reverse=True)
    return scored_clauses[:max_clauses]


def build_grounded_citations_text(query: str) -> str:
    """Формирует блок цитат для контекста LLM."""
    clauses = retrieve_normative_clauses(query, max_clauses=3)
    if not clauses:
        return "Действующие нормативные акты РФ: СанПиН 3.3686-21, Федеральный закон № 52-ФЗ, ГОСТ Р 7.0.97-2016."
    
    lines = ["ВЕРИФИЦИРОВАННЫЙ НОРМАТИВНЫЙ КОНТЕКСТ (СТРОГО ОПИРАТЬСЯ НА ДАННЫЕ ПУНКТЫ):"]
    for c in clauses:
        lines.append(f"• {c['act']} ({c['clause']} — {c['topic']}):\n  «{c['text']}»")
    return "\n\n".join(lines)
